test("nothing is written when validation fails after moving", () => {
  const root = project({
    "docs/issues/0001-a.md": issue({ id: "0001", title: "A", status: "done" }, "\n[bad](missing.md) [b](0002-b.md)\n"),
    "docs/issues/0002-b.md": issue({ id: "0002", title: "B", status: "open" }, "\n[a](0001-a.md)\n"),
  });
  const before = { a: read(root, "docs/issues/0001-a.md"), b: read(root, "docs/issues/0002-b.md") };
  const r = run(root);
  assert.equal(r.code, 1);
  // Reported as on disk: the file was not moved and the link not rewritten.
  assert.match(r.stderr, /issues\/0001-a\.md: link target does not exist → missing\.md\n/);
  assert.doesNotMatch(r.stdout, /Moved/);
  assert.equal(read(root, "docs/issues/0001-a.md"), before.a);
  assert.equal(read(root, "docs/issues/0002-b.md"), before.b);
  assert.ok(!exists(root, "docs/issues/done"));
  assert.ok(!exists(root, "docs/issues/README.md"));
});

test("new and set leave no changes behind when validation fails", () => {
  const root = project({
    "docs/issues/0001-a.md": issue({ id: "0001", title: "A", status: "open" }, "\n[bad](missing.md)\n"),
  });
  const before = read(root, "docs/issues/0001-a.md");

  const n = run(root, "new", "Second");
  assert.equal(n.code, 1);
  assert.doesNotMatch(n.stdout, /Created/);
  assert.ok(!exists(root, "docs/issues/0002-second.md"));

  const s = run(root, "set", "1", "status=done");
  assert.equal(s.code, 1);
  assert.doesNotMatch(s.stdout, /Updated/);
  assert.equal(read(root, "docs/issues/0001-a.md"), before);
  assert.ok(!exists(root, "docs/issues/done"));
});

