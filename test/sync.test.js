import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { project, write, read, exists, run, issue } from "./helpers.js";

const base = () =>
  project({
    "package.json": { scripts: { issues: "md-issues", "check:issues": "md-issues check" } },
    "issues/0001-first.md": issue({ id: "0001", title: "First", status: "open", related: ["0002"] }, "\nSee [second](0002-second.md#details).\n"),
    "issues/0002-second.md": issue({ id: "0002", title: "Second", status: "done" }, "\n## Details\n\nBack to [first](0001-first.md) and [docs](../docs/guide.md).\n"),
    "docs/guide.md": "# Guide\n\nTracked in [0002](../issues/0002-second.md).\n",
    "issues/config.json": { linkFiles: ["docs/*.md"] },
  });

test("moves closed issues, rewrites links and generates the index", () => {
  const root = base();
  const r = run(root);
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /Moved: issues\/0002-second\.md → issues\/done\/0002-second\.md/);
  assert.ok(exists(root, "issues/done/0002-second.md"));
  assert.match(read(root, "issues/0001-first.md"), /\[second\]\(done\/0002-second\.md#details\)/);
  const moved = read(root, "issues/done/0002-second.md");
  assert.match(moved, /\[first\]\(\.\.\/0001-first\.md\)/);
  assert.match(moved, /\[docs\]\(\.\.\/\.\.\/docs\/guide\.md\)/);
  assert.match(read(root, "docs/guide.md"), /\(\.\.\/issues\/done\/0002-second\.md\)/);

  const index = read(root, "issues/README.md");
  assert.match(index, /generated by `npm run issues`/);
  assert.match(index, /2 issues — Open 1 \/ Done 1 \/ Won't fix 0/);
  assert.match(index, /\| \[0002\]\(done\/0002-second\.md\) \| Second \| Done \|/);

  assert.equal(run(root, "check").code, 0);
});

test("check changes nothing and fails when files are misplaced or the index is stale", () => {
  const root = base();
  const r = run(root, "check");
  assert.equal(r.code, 1);
  assert.match(r.stderr, /should be at issues\/done\/0002-second\.md \(run `npm run issues`\)/);
  assert.ok(exists(root, "issues/0002-second.md"));

  run(root);
  write(root, "issues/README.md", "stale\n");
  const s = run(root, "check");
  assert.equal(s.code, 1);
  assert.match(s.stderr, /out of date/);
});

test("validation errors exit with 1", () => {
  const root = project({
    "issues/0001-a.md": issue({ id: "0002", title: "A", status: "nope", related: ["0009"] }),
    "issues/bad.md": "x",
    "issues/0003-c.md": "no frontmatter",
  });
  const r = run(root);
  assert.equal(r.code, 1);
  for (const re of [/id \(0002\) does not match/, /invalid status \(nope\)/, /related issue 0009/, /bad\.md: file name/, /0003-c\.md: no frontmatter/]) {
    assert.match(r.stderr, re);
  }
});

test("configured vocabulary, required keys and Japanese output", () => {
  const root = project({
    "issues/config.json": {
      lang: "ja",
      severity: ["高", "低"],
      required: ["severity", "scope"],
      fields: { scope: ["a", "b"], origin: "^T\\d+$" },
      columns: ["id", "title", "severity", "status", { label: "由来", fields: ["origin", "commits"] }],
    },
    "issues/0001-a.md": issue({ id: "0001", title: "A", status: "open", severity: "低", scope: "a", origin: "T1", commits: ["abc1234"] }),
    "issues/0002-b.md": issue({ id: "0002", title: "B", status: "doing", severity: "高", scope: "a" }),
  });
  const r = run(root);
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /を生成しました（2 件）/);
  const index = read(root, "issues/README.md");
  assert.match(index, /全 2 件 — 未対応 2（高 1 \/ 低 1） \/ 完了 0 \/ 対応しない 0/);
  assert.match(index, /\| # \| 項目 \| 深刻度 \| 状態 \| 由来 \|/);
  assert.ok(index.indexOf("[0002]") < index.indexOf("[0001]"), "sorted by severity");
  assert.match(index, /\| T1 `abc1234` \|/);
  assert.match(index, /## 書き方/);

  write(root, "issues/0001-a.md", issue({ id: "0001", title: "A", status: "open", severity: "中", origin: "X" }));
  const bad = run(root, "check");
  assert.equal(bad.code, 1);
  assert.match(bad.stderr, /frontmatter に scope がありません/);
  assert.match(bad.stderr, /severity が不正です \(中\)/);
  assert.match(bad.stderr, /origin が不正です \(X\) → \/\^T\\d\+\$\/ に合いません/);
});

test("GUIDE.md replaces the default guide", () => {
  const root = project({ "issues/0001-a.md": issue({ id: "0001", title: "A", status: "open" }), "issues/GUIDE.md": "## Our rules\n" });
  run(root);
  assert.match(read(root, "issues/README.md"), /---\n\n## Our rules\n$/);
});

test("broken links and anchors are reported", () => {
  const root = project({
    "issues/0001-a.md": issue({ id: "0001", title: "A", status: "open" }, "\n[x](missing.md) [y](0002-b.md#nope) [z]() [w](#here)\n\n## Here\n"),
    "issues/0002-b.md": issue({ id: "0002", title: "B", status: "open" }),
  });
  const r = run(root);
  assert.equal(r.code, 1);
  assert.match(r.stderr, /link target does not exist → missing\.md/);
  assert.match(r.stderr, /heading not found → 0002-b\.md#nope/);
  assert.match(r.stderr, /empty link target/);
  assert.doesNotMatch(r.stderr, /#here/);
});

test("linkFiles that match nothing are configuration errors", () => {
  const root = project({ "issues/config.json": { linkFiles: ["docs/**/*.md"] }, "issues/0001-a.md": issue({ id: "0001", title: "A", status: "open" }) });
  const r = run(root);
  assert.equal(r.code, 2);
  assert.match(r.stderr, /matches no files/);
});

test("custom statuses and stray files", () => {
  const root = project({
    "issues/config.json": {
      status: { todo: { group: "a", dir: "" }, closed: { group: "b", dir: "archive" } },
      groups: [{ id: "a", label: "Todo", summary: true }, { id: "b", label: "Closed" }],
    },
    "issues/0001-a.md": issue({ id: "0001", title: "A", status: "closed" }),
    "issues/done/0002-b.md": issue({ id: "0002", title: "B", status: "todo" }),
  });
  const r = run(root);
  assert.equal(r.code, 0, r.stderr);
  assert.ok(exists(root, "issues/archive/0001-a.md"));
  assert.match(r.stderr, /Warning: issues\/done\/0002-b\.md is not in a directory used by any status/);
});

test("checkCommits verifies hashes with git", () => {
  const root = project({ "issues/0001-a.md": issue({ id: "0001", title: "A", status: "open", commits: ["deadbee"] }), "issues/config.json": { checkCommits: true } });
  execFileSync("git", ["init", "-q"], { cwd: root });
  run(root);
  const r = run(root, "check");
  assert.equal(r.code, 1);
  assert.match(r.stderr, /commit deadbee does not exist/);
});

test("missing issue directory and bad options exit with 2", () => {
  const root = project({ "package.json": {} });
  assert.equal(run(root).code, 2);
  assert.match(run(root).stderr, /Create it with `md-issues init`/);
  assert.equal(run(root, "--nope").code, 2);
  assert.equal(run(root, "extra").code, 2);
  assert.equal(run(root, "check", "extra").code, 2);
});

test("the options replaced by subcommands point to them", () => {
  const root = project();
  for (const [option, command] of [["--check", "check"], ["-c", "check"], ["--init", "init"], ["-i", "init"]]) {
    const r = run(root, option);
    assert.equal(r.code, 2);
    assert.match(r.stderr, new RegExp(`${option} has been replaced by \`md-issues ${command}\``));
  }
});
