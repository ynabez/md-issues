test("custom statuses; issue files anywhere are read, other Markdown is a warning", () => {
  const root = project({
    "docs/issues/config.json": {
      status: { todo: { group: "a", dir: "" }, closed: { group: "b", dir: "archive" } },
      groups: [{ id: "a", label: "Todo", summary: true }, { id: "b", label: "Closed" }],
    },
    "docs/issues/0001-a.md": issue({ id: "0001", title: "A", status: "closed" }),
    "docs/issues/done/0002-b.md": issue({ id: "0002", title: "B", status: "todo" }),
    "docs/issues/notes/ideas.md": "# Ideas\n",
  });
  const r = run(root);
  assert.equal(r.code, 0, r.stderr);
  assert.ok(exists(root, "docs/issues/archive/0001-a.md"));
  assert.ok(exists(root, "docs/issues/0002-b.md"), "moved out of a directory no status uses");
  assert.match(r.stdout, /Moved: docs\/issues\/done\/0002-b\.md → docs\/issues\/0002-b\.md/);
  assert.match(r.stderr, /Warning: docs\/issues\/notes\/ideas\.md is not an issue file/);
  assert.match(read(root, "docs/issues/README.md"), /2 issues — Todo 1 \/ Closed 1/);
});

test("an issue in a directory the configuration dropped is not silently left out", () => {
  const root = project({
    "docs/issues/config.json": { status: { open: { group: "active" } }, groups: [{ id: "active" }] },
    "docs/issues/done/0001-a.md": issue({ id: "0001", title: "A", status: "done" }),
  });
  for (const args of [[], ["check"]]) {
    const r = run(root, ...args);
    assert.equal(r.code, 1, args.join(" "));
    assert.match(r.stderr, /issues\/done\/0001-a\.md: invalid status \(done\) → open/);
  }
  assert.ok(!exists(root, "docs/issues/README.md"));
});

