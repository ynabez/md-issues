test("broken links and anchors are reported", () => {
  const root = project({
    "docs/issues/0001-a.md": issue({ id: "0001", title: "A", status: "open" }, "\n[x](missing.md) [y](0002-b.md#nope) [z]() [w](#here)\n\n## Here\n"),
    "docs/issues/0002-b.md": issue({ id: "0002", title: "B", status: "open" }),
  });
  const r = run(root);
  assert.equal(r.code, 1);
  assert.match(r.stderr, /link target does not exist → missing\.md/);
  assert.match(r.stderr, /heading not found → 0002-b\.md#nope/);
  assert.match(r.stderr, /empty link target/);
  assert.doesNotMatch(r.stderr, /#here/);
});

